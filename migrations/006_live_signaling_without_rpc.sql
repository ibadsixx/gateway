-- Tone Live — PHASE 7 signaling schema without custom SQL functions.
--
-- Supabase is database-only. All ticket/message business logic lives in the
-- existing Next.js Gateway. This migration deliberately creates NO function,
-- NO RPC, and NO application logic in PostgreSQL.
--
-- The two tables are the only shared coordination state for WebSockets pinned
-- to separate Vercel Function instances. They are accessed only by the Gateway
-- service-role client; browser clients have no table access.

-- ---------------------------------------------------------------------------
-- 1. Short-lived, single-use WebSocket connection tickets.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS live_signaling_tickets (
  token_hash   TEXT PRIMARY KEY,
  session_id   TEXT NOT NULL,
  user_id      TEXT NOT NULL,
  role         TEXT NOT NULL CHECK (role IN ('host', 'moderator', 'guest', 'viewer')),
  expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed_at  TIMESTAMP WITH TIME ZONE,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_live_signaling_tickets_session
  ON live_signaling_tickets(session_id);
CREATE INDEX IF NOT EXISTS idx_live_signaling_tickets_expires
  ON live_signaling_tickets(expires_at);
CREATE INDEX IF NOT EXISTS idx_live_signaling_tickets_unconsumed
  ON live_signaling_tickets(consumed_at) WHERE consumed_at IS NULL;

-- ---------------------------------------------------------------------------
-- 2. Durable signaling messages with a database-generated cursor.
-- ---------------------------------------------------------------------------
-- `seq` is a BIGINT GENERATED BY DEFAULT AS IDENTITY: PostgreSQL allocates a
-- globally unique, monotonic cursor on INSERT. No sequence function, clock, or
-- per-instance counter is involved. `id` remains the client idempotency key.
CREATE TABLE IF NOT EXISTS live_signaling_messages (
  id            TEXT PRIMARY KEY,
  seq           BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  session_id    TEXT NOT NULL,
  from_user_id  TEXT NOT NULL,
  to_user_id    TEXT,
  type          TEXT NOT NULL,
  role          TEXT NOT NULL,
  sdp           TEXT,
  candidate     JSONB,
  state         JSONB,
  expires_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Compatibility repair only: if a partial Phase 4/5 deployment created the
-- table with a plain BIGINT seq column, add identity without dropping data and
-- align the generator to the largest existing cursor. This is migration DDL,
-- not a stored function or application RPC.
DO $phase7$
DECLARE
  max_existing_seq BIGINT;
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'live_signaling_messages'
      AND column_name = 'seq'
      AND is_identity = 'NO'
  ) THEN
    EXECUTE 'ALTER TABLE live_signaling_messages ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY';
    SELECT COALESCE(MAX(seq), 0) INTO max_existing_seq FROM live_signaling_messages;
    EXECUTE format(
      'SELECT setval(pg_get_serial_sequence(%L, %L), GREATEST(%s, 1), %L)',
      'live_signaling_messages',
      'seq',
      max_existing_seq,
      max_existing_seq > 0
    );
  END IF;
END
$phase7$;

CREATE INDEX IF NOT EXISTS idx_live_signaling_messages_session_seq
  ON live_signaling_messages(session_id, seq);
CREATE INDEX IF NOT EXISTS idx_live_signaling_messages_recipient
  ON live_signaling_messages(session_id, to_user_id, seq);
CREATE INDEX IF NOT EXISTS idx_live_signaling_messages_expires
  ON live_signaling_messages(expires_at);

-- RLS is intentionally NOT enabled. These Gateway-only tables are not exposed
-- to browser clients. Authentication, audience checks, payload validation,
-- rate limits, idempotency, and expiry remain Gateway responsibilities.

-- The legacy objects live_signaling_message_seq and
-- next_live_signaling_message_seq() are intentionally NOT dropped here. The
-- old Gateway may still be running during a rolling deployment. Remove them in
-- a later maintenance migration only after the new Gateway is deployed and
-- production verification proves no instance calls the RPC.
